def generate_rsa_keys_and_sign(bits=2048, exchange_hash=EXCHANGE_HASH_SAMPLE):
    """Generate RSA key pair and sign the exchange hash."""
    private_key = rsa.generate_private_key(
        public_exponent=65537,
        key_size=bits,
    )

    public_key = private_key.public_key()
    pub_numbers = public_key.public_numbers()

    signature = private_key.sign(
        exchange_hash,
        padding.PKCS1v15(),
        hashes.SHA256(),
    )

    return {"public": pub_numbers.n.to_bytes(256, byteorder="big"), "signature": signature}  # 256 bytes for RSA-2048


def generate_dsa_keys_and_sign(bits=1024, exchange_hash=EXCHANGE_HASH_SAMPLE):
    """Generate DSA key pair and sign the exchange hash."""
    parameters = dsa.generate_parameters(bits)
    private_key = parameters.generate_private_key()

    pub_numbers = private_key.public_key().public_numbers()

    signature = private_key.sign(
        exchange_hash,
        hashes.SHA1(),
    )

    return {
        "public": pub_numbers.y.to_bytes(128, byteorder="big"),
        "signature": signature,  # ~40-48 bytes (DER encoded r+s)
    }


def generate_ed25519_keys_and_sign(exchange_hash=EXCHANGE_HASH_SAMPLE):
    """Generate ed25519 key pair and sign the exchange hash."""
    private_key = Ed25519PrivateKey.generate()
    public_key = private_key.public_key()

    signature = private_key.sign(exchange_hash)

    return {
        "public": public_key.public_bytes(encoding=serialization.Encoding.Raw, format=serialization.PublicFormat.Raw),
        "signature": signature,  # Always 64 bytes for Ed25519
    }


def generate_curve25519_public_key():
    """Generate Curve25519 public key (32 bytes)."""
    private = nacl.public.PrivateKey.generate()
    public = private.public_key
    return bytes(public)


def generate_dh_group14_public_key(parameters):
    """Generate DH Group 14 public key (256 bytes = 2048 bits)."""
    private = parameters.generate_private_key()
    public = private.public_key()
    pub_num = public.public_numbers()
    return pub_num.y.to_bytes(256, byteorder="big")


def generate_nistp256_public_key():
    """Generate NIST P-256 EC public key (65 bytes = 0x04 + X + Y)."""
    private = ec.generate_private_key(ec.SECP256R1(), default_backend())
    public = private.public_key()
    return public.public_bytes(
        encoding=serialization.Encoding.X962, format=serialization.PublicFormat.UncompressedPoint
    )


def format_byte_array(key_bytes, indent=8, bytes_per_line=16):
    """Format bytes into correct format"""
    indent_str = " " * indent
    lines = []

    for i in range(0, len(key_bytes), bytes_per_line):
        chunk = key_bytes[i : i + bytes_per_line]
        byte_str = ", ".join(f"0x{b:02x}" for b in chunk)
        if i + bytes_per_line < len(key_bytes):
            lines.append(f"{indent_str}{byte_str},")
        else:
            lines.append(f"{indent_str}{byte_str}")

    return "\n".join(lines)


def insert_rsa(output_string):
    """Insert the RSA keys and signatures into output string"""
    print("Generating RSA keys and singatures")
    rsa_keys = [generate_rsa_keys_and_sign(2048) for _ in range(ALG_NUM)]
    src = ""
    for i, key_data in enumerate(rsa_keys):
        print(f"Key: {i+1}/{ALG_NUM}")
        src += "{{"
        src += format_byte_array(key_data["public"], indent=8)
        src += "}},"
    output_string = output_string.replace("//<<<INSERT SSH_RSA_2048_KEYS HERE>>>", src)

    src = ""
    for i, key_data in enumerate(rsa_keys):
        print(f"Sig: {i+1}/{ALG_NUM}")

        sig_bytes = key_data["signature"]
        if len(sig_bytes) < 256:
            sig_bytes = b"\x00" * (256 - len(sig_bytes)) + sig_bytes

        src += "{{"
        src += format_byte_array(sig_bytes[:256], indent=8)
        src += "}},"
    output_string = output_string.replace("//<<<INSERT SSH_RSA_2048_SIGNATURES>>>", src)
    return output_string


